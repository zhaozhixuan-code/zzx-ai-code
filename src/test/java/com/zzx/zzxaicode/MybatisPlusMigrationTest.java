import static org.junit.jupiter.api.Assertions.*;

/** 验证迁移后实体映射、逻辑删除和分页响应的关键行为。 */
@MybatisPlusTest(properties = {
        "spring.datasource.url=jdbc:h2:mem:migration;MODE=MySQL;DB_CLOSE_DELAY=-1;NON_KEYWORDS=USER",
        "spring.datasource.driver-class-name=org.h2.Driver",
        "spring.datasource.username=sa",
        "spring.datasource.password=",
        "mybatis-plus.configuration.map-underscore-to-camel-case=false"
})
@AutoConfigureTestDatabase(replace = AutoConfigureTestDatabase.Replace.NONE)
@ContextConfiguration(classes = MybatisPlusMigrationTest.TestApplication.class)
class MybatisPlusMigrationTest {
    @TestConfiguration
    @EnableAutoConfiguration
    @MapperScan("com.zzx.zzxaicode.mapper")
    @Import(MybatisPlusConfig.class)
    static class TestApplication { }

    @Autowired private JdbcTemplate jdbc;
    @Autowired private AppMapper appMapper;
    @Autowired private UserMapper userMapper;
    @Autowired private ChatHistoryMapper chatHistoryMapper;

    /** 创建与业务字段对应的临时表，测试结束由事务回滚数据。 */
    @BeforeEach
    void createTables() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS app (id BIGINT PRIMARY KEY, appName VARCHAR(256), cover VARCHAR(512), initPrompt VARCHAR(512), codeGenType VARCHAR(64), deployKey VARCHAR(64), deployedTime TIMESTAMP, priority INT DEFAULT 0, userId BIGINT, editTime TIMESTAMP, createTime TIMESTAMP, updateTime TIMESTAMP, isDelete INT DEFAULT 0)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS user (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, userAccount VARCHAR(256), userPassword VARCHAR(512), userName VARCHAR(256), userAvatar VARCHAR(1024), userProfile VARCHAR(512), userRole VARCHAR(256), editTime TIMESTAMP, createTime TIMESTAMP, updateTime TIMESTAMP, isDelete INT DEFAULT 0)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS chat_history (id BIGINT PRIMARY KEY, message VARCHAR(512), messageType VARCHAR(32), appId BIGINT, userId BIGINT, createTime TIMESTAMP, updateTime TIMESTAMP, isDelete INT DEFAULT 0)");
        jdbc.update("DELETE FROM app");
        jdbc.update("DELETE FROM user");
        jdbc.update("DELETE FROM chat_history");
    }

    /** 验证两类主键生成、驼峰列读写以及删除后的自动过滤。 */
    @Test
    void mapsFieldsAndLogicalDeletes() {
        User user = User.builder().userAccount("account").userPassword("password").build();
        assertEquals(1, userMapper.insert(user));
        assertNotNull(user.getId());
        assertEquals("account", userMapper.selectById(user.getId()).getUserAccount());
        App app = App.builder().appName("first").userId(user.getId()).build();
        assertEquals(1, appMapper.insert(app));
        assertNotNull(app.getId());
        ChatHistory history = ChatHistory.builder().appId(app.getId()).userId(user.getId()).message("hi").messageType("user").build();
        assertEquals(1, chatHistoryMapper.insert(history));
        assertNotNull(history.getId());
        assertEquals("user", chatHistoryMapper.selectById(history.getId()).getMessageType());
        assertEquals(1, chatHistoryMapper.deleteById(history.getId()));
        assertNull(chatHistoryMapper.selectById(history.getId()));
        assertEquals(1, jdbc.queryForObject("SELECT isDelete FROM chat_history WHERE id = ?", Integer.class, history.getId()));
        assertEquals(1, userMapper.deleteById(user.getId()));
        assertNull(userMapper.selectById(user.getId()));
        assertEquals(1, appMapper.deleteById(app.getId()));
        assertNull(appMapper.selectById(app.getId()));
    }

    /** 验证可选条件、分页总数和客户端依赖的分页 JSON 字段。 */
    @Test
    void filtersAndPaginatesWithNativeJson() throws Exception {
        for (int i = 0; i < 3; i++) {
            appMapper.insert(App.builder().appName("match " + i).userId(7L).build());
        }
        appMapper.insert(App.builder().appName("other").userId(8L).build());
        AppQueryRequest request = new AppQueryRequest();
        request.setUserId(7L);
        request.setAppName("match");
        request.setSortField("id");
        request.setSortOrder("ascend");
        Page<App> page = appMapper.selectPage(Page.of(2, 2), new AppServiceImpl().getQueryWrapper(request));
        assertEquals(3, page.getTotal());
        assertEquals(2, page.getPages());
        assertEquals(1, page.getRecords().size());
        assertEquals(7L, page.getRecords().getFirst().getUserId());
        JsonNode json = new ObjectMapper().findAndRegisterModules().valueToTree(page);
        assertEquals(3, json.get("total").asInt());
        assertEquals(2, json.get("current").asInt());
        assertEquals(2, json.get("size").asInt());
        assertEquals(1, json.get("records").size());
        AppQueryRequest empty = new AppQueryRequest();
        assertEquals(4, appMapper.selectCount(new AppServiceImpl().getQueryWrapper(empty)));
    }
    /** 验证聊天游标严格早于指定时间，并排除其他应用和已删除记录。 */
    @Test
    void chatCursorFiltersAtBoundary() {
        LocalDateTime cursor = LocalDateTime.of(2026, 1, 1, 12, 0);
        ChatHistory earlier = ChatHistory.builder().appId(1L).userId(3L).message("before").messageType("user").createTime(cursor.minusSeconds(1)).build();
        ChatHistory boundary = ChatHistory.builder().appId(1L).userId(3L).message("boundary").messageType("user").createTime(cursor).build();
        ChatHistory other = ChatHistory.builder().appId(2L).userId(3L).message("other").messageType("user").createTime(cursor.minusSeconds(2)).build();
        ChatHistory deleted = ChatHistory.builder().appId(1L).userId(3L).message("deleted").messageType("user").createTime(cursor.minusSeconds(3)).build();
        chatHistoryMapper.insert(earlier);
        chatHistoryMapper.insert(boundary);
        chatHistoryMapper.insert(other);
        chatHistoryMapper.insert(deleted);
        chatHistoryMapper.deleteById(deleted.getId());
        ChatHistoryQueryRequest request = new ChatHistoryQueryRequest();
        request.setAppId(1L);
        request.setLastCreateTime(cursor);
        Page<ChatHistory> page = chatHistoryMapper.selectPage(Page.of(1, 10), new ChatHistoryServiceImpl().getQueryWrapper(request));
        assertEquals(1, page.getTotal());
        assertEquals("before", page.getRecords().getFirst().getMessage());
    }

    /** 验证公开项目列表只包含有非空部署标识和部署时间的应用。 */
    @Test
    void deployedListExcludesDrafts() {
        LocalDateTime deployed = LocalDateTime.of(2026, 1, 1, 12, 0);
        appMapper.insert(App.builder().appName("published").userId(1L).deployKey("key").deployedTime(deployed).build());
        appMapper.insert(App.builder().appName("blank").userId(1L).deployKey("  ").deployedTime(deployed).build());
        appMapper.insert(App.builder().appName("draft").userId(1L).deployKey("key2").build());
        QueryWrapper<App> query = new QueryWrapper<App>()
                .apply("deployKey IS NOT NULL AND TRIM(deployKey) <> '' AND deployedTime IS NOT NULL")
                .orderByDesc("deployedTime", "id");
        Page<App> page = appMapper.selectPage(Page.of(1, 10), query);
        assertEquals(1, page.getTotal());
        assertEquals("published", page.getRecords().getFirst().getAppName());
    }
}
